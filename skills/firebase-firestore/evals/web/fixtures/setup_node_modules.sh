#!/bin/bash
set -euo pipefail

HARNESS_DIR="/tmp/firestore_eval_harness"
mkdir -p "${HARNESS_DIR}"

cat << 'NPMRC' > "${HARNESS_DIR}/.npmrc"
registry=http://airlock-proxy.uplink.goog:999/npm/artifact-foundry-prod/ah-3p-staging-npm/
replace-registry-host=false
NPMRC

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cp "${SCRIPT_DIR}/package.json" "${HARNESS_DIR}/"
# Clean up accidental recursive node_modules if present
rm -rf "${HARNESS_DIR}/node_modules/node_modules"

if [ ! -d "${HARNESS_DIR}/node_modules/firebase" ]; then
  echo "Installing/updating Firestore eval node_modules in ${HARNESS_DIR}..."
  npm --prefix "${HARNESS_DIR}" update --omit=optional
fi

# Stage mock firebase CLI into harness bin for hermetic CLI inspection cases
mkdir -p "${HARNESS_DIR}/node_modules/.bin"
cp "${SCRIPT_DIR}/bin/firebase" "${HARNESS_DIR}/node_modules/.bin/firebase"
cp "${SCRIPT_DIR}/bin/firebase" "${HARNESS_DIR}/node_modules/.bin/firebase-tools"
chmod +x "${HARNESS_DIR}/node_modules/.bin/firebase" "${HARNESS_DIR}/node_modules/.bin/firebase-tools"
